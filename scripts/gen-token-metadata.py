#!/usr/bin/env python3
"""Generate crates/rpsh-syntax/src/full_token_kind.rs from inventory/token-kinds.tsv."""
from pathlib import Path
import re
import json

ROOT = Path(__file__).resolve().parent.parent
ROWS = []
for line in (ROOT / 'inventory/token-kinds.tsv').read_text(encoding='utf-8').splitlines()[1:]:
    fields = line.split('\t')
    if len(fields) < 3:
        continue
    kind, text, flags = fields[0], fields[1], fields[2]
    if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', kind):
        raise SystemExit(f'not a Rust identifier: {kind!r}')
    ROWS.append((kind, text, [flag for flag in flags.split(',') if flag and flag != 'None']))

flags_names = sorted({flag for _, _, flags in ROWS for flag in flags})
flag_consts = '\n'.join(
    f'    pub const {re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()}: TokenFlags = TokenFlags(1 << {index});'
    for index, name in enumerate(flags_names)
)
flag_bits = {name: index for index, name in enumerate(flags_names)}
variants = '\n'.join(f'    {kind},' for kind, _, _ in ROWS)
name_arms = '\n'.join(f'            Self::{kind} => "{kind}",' for kind, _, _ in ROWS)
flag_arms = '\n'.join(
    '            Self::{} => TokenFlags({}),'.format(
        kind,
        ' | '.join(f'1 << {flag_bits[flag]}' for flag in flags) if flags else '0',
    )
    for kind, _, flags in ROWS
)
table = '\n'.join(
    '    TokenKindInfo {{ kind: FullTokenKind::{kind}, text: {text}, flags: FullTokenKind::{kind}.flags() }},'.format(
        kind=kind, text=json.dumps(text)
    )
    for kind, text, _ in ROWS
)
output = f'''// @generated by scripts/gen-token-metadata.py from inventory/token-kinds.tsv.
// Do not edit by hand. Regenerate after scripts/gen-inventory.ps1.

/// Every token kind the reference tokenizer can produce.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum FullTokenKind {{
{variants}
}}

/// The flags the reference tokenizer records for a kind.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TokenFlags(pub u64);

impl TokenFlags {{
{flag_consts}
}}

impl FullTokenKind {{
    pub const ALL: &'static [FullTokenKind] = &[
{''.join(f'        Self::{kind},\n' for kind, _, _ in ROWS)}    ];

    pub fn name(self) -> &'static str {{
        match self {{
{name_arms}
        }}
    }}

    pub const fn flags(self) -> TokenFlags {{
        match self {{
{flag_arms}
        }}
    }}
}}

/// The raw row from inventory/token-kinds.tsv.
#[derive(Debug, Clone, Copy)]
pub struct TokenKindInfo {{
    pub kind: FullTokenKind,
    pub text: &'static str,
    pub flags: TokenFlags,
}}

pub static TOKEN_KINDS: &[TokenKindInfo] = &[
{table}
];
'''
out = ROOT / 'crates/rpsh-syntax/src/full_token_kind.rs'
out.write_text(output, encoding='utf-8')
print(f'wrote {{}} kinds'.format(len(ROWS)))
