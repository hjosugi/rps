#!/usr/bin/env python3
"""Regenerate crates/rpsh-messages/src/catalog.rs from upstream's resources.

The source is the latest stable PowerShell release tag, resolved from GitHub
when the script runs. The archive is downloaded and its SHA-256 is recorded in
the generated header, so a catalog can be traced to the tree it came from and
regenerated by passing the same `--tag`. Only the neutral `.resx` files are
read: the ones directly below a project's `resources/` directory. The
localized copies under `resources/<culture>/` are ignored, because the Linux
release ships no satellite assemblies and prints English under every `LANG`
(docs/01_compat_contract.md, "Errors and messages").

    scripts/gen-messages.py                 # latest stable release
    scripts/gen-messages.py --tag <tag>      # reproduce a recorded catalog
    scripts/gen-messages.py --source DIR    # use an already extracted tree
    scripts/gen-messages.py --check         # fail if the tree is out of date

The generated file is sorted by key so the runtime can binary-search it.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
import tarfile
import tempfile
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "crates/rpsh-messages/src/catalog.rs"
GITHUB_LATEST = "https://github.com/PowerShell/PowerShell/releases/latest"


def latest_stable_tag() -> str:
    """The tag of the latest stable PowerShell release."""
    request = urllib.request.Request(GITHUB_LATEST, method="HEAD")
    with urllib.request.urlopen(request) as response:
        return response.url.rstrip("/").rsplit("/", 1)[-1]


def archive_url(tag: str) -> str:
    return f"https://codeload.github.com/PowerShell/PowerShell/tar.gz/refs/tags/{tag}"


def cache_path(tag: str) -> Path:
    return ROOT / ".cache/upstream" / f"PowerShell-{tag}.tar.gz"


def download(tag: str) -> tuple[Path, str]:
    """Fetch the tag's archive into .cache/ and return it with its SHA-256."""
    cache = cache_path(tag)
    if cache.exists():
        return cache, hashlib.sha256(cache.read_bytes()).hexdigest()
    cache.parent.mkdir(parents=True, exist_ok=True)
    url = archive_url(tag)
    print(f"gen-messages: downloading {url}", file=sys.stderr)
    with urllib.request.urlopen(url) as response, \
            tempfile.NamedTemporaryFile(dir=cache.parent, delete=False) as temp:
        digest = hashlib.sha256()
        while chunk := response.read(1 << 20):
            digest.update(chunk)
            temp.write(chunk)
        Path(temp.name).replace(cache)
    return cache, hashlib.sha256(cache.read_bytes()).hexdigest()


def resx_files(source: Path):
    """Yield `(relative path, bytes)` for each neutral resource file."""
    for path in sorted(source.glob("**/resources/*.resx")):
        if path.parent.name == "resources":
            yield path.relative_to(source).as_posix(), path.read_bytes()


def resx_files_from_archive(archive: Path):
    """Yield `(relative path, bytes)` from a source archive."""
    with tarfile.open(archive, "r:gz") as tar:
        members = sorted(tar.getmembers(), key=lambda member: member.name)
        for member in members:
            path = PurePosixPath(member.name)
            if path.parent.name != "resources" or path.suffix != ".resx":
                continue
            # Drop the archive's `PowerShell-<version>/` root.
            relative = PurePosixPath(*path.parts[1:]).as_posix()
            file = tar.extractfile(member)
            if file is not None:
                yield relative, file.read()


def rust_string(value: str) -> str:
    """Quote `value` as a Rust string literal."""
    out = ['"']
    for char in value:
        code = ord(char)
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif code < 0x20 or code == 0x7F:
            out.append(f"\\u{{{code:x}}}")
        else:
            out.append(char)
    out.append('"')
    return "".join(out)


def build(files, tag: str, digest: str) -> tuple[str, int, int]:
    entries: dict[str, str] = {}
    file_count = 0
    for relative, data in files:
        file_count += 1
        base = PurePosixPath(relative).name[: -len(".resx")]
        root = ET.fromstring(data)
        for item in root.findall("data"):
            name = item.get("name")
            value = item.findtext("value")
            if name is None or value is None:
                continue
            key = f"{base}/{name}"
            if key in entries:
                raise SystemExit(f"gen-messages: duplicate message {key!r} in {relative}")
            entries[key] = value

    lines = [
        "// @generated by scripts/gen-messages.py.",
        f"// Source: PowerShell {tag} (archive SHA-256 {digest}).",
        "// Neutral .resx resources, MIT. Sorted by key for binary search.",
        "",
        "#[rustfmt::skip]",
        "pub(crate) static CATALOG: &[(&str, &str)] = &[",
    ]
    for key in sorted(entries):
        lines.append(f"    ({rust_string(key)}, {rust_string(entries[key])}),")
    lines.append("];")
    lines.append("")
    return "\n".join(lines), file_count, len(entries)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--tag",
        help="the release tag to extract (default: the latest stable release)",
    )
    parser.add_argument(
        "--source",
        type=Path,
        help="an extracted PowerShell source tree (skips the download)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed catalog differs instead of writing it",
    )
    args = parser.parse_args()

    tag = args.tag or latest_stable_tag()
    if args.source is not None:
        files = resx_files(args.source)
        digest = "unknown (extracted source tree)"
        generated, file_count, message_count = build(files, tag, digest)
    else:
        archive, digest = download(tag)
        generated, file_count, message_count = build(
            resx_files_from_archive(archive), tag, digest
        )

    print(
        f"gen-messages: PowerShell {tag}, {file_count} neutral .resx files, "
        f"{message_count} messages, {len(generated)} bytes"
    )

    if args.check:
        current = CATALOG.read_text(encoding="utf-8") if CATALOG.exists() else ""
        if current != generated:
            print(f"gen-messages: {CATALOG} is out of date", file=sys.stderr)
            return 1
        return 0

    CATALOG.parent.mkdir(parents=True, exist_ok=True)
    CATALOG.write_text(generated, encoding="utf-8", newline="\n")
    print(f"gen-messages: wrote {CATALOG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
